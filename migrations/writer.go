// ErrNotSerializable is returned by RenderMigration for an operation that has
// no Go source form: RunGo, whose functions cannot be printed, and operation
// types defined outside this package.
var ErrNotSerializable = errors.New("migrations: operation cannot be written as Go source")

// PackageName returns the Go package name for the migrations of an app: the
// app label where it is a usable identifier, and "migrations" otherwise.
func PackageName(app string) string {
	if isValidGoIdent(app) && !token.IsKeyword(app) && app != "_" && app != "init" && app != "main" {
		return app
	}
	return "migrations"
}

// FileName returns the file name of the migration name. The Go tool gives a
// meaning to some endings ("_test", "_linux", "_amd64"), which would keep the
// file out of the build; such a name gets one more underscore.
func FileName(name string) string {
	if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
		name = "m" + name
	}
	if hasBuildSuffix(name) {
		name += "_"
	}
	return name + ".go"
}

// buildSuffixes are the file-name endings the Go tool reads as a constraint:
// the known operating systems and architectures, and "test".
var buildSuffixes = map[string]bool{
	"test": true,
	// Operating systems.
	"aix": true, "android": true, "darwin": true, "dragonfly": true, "freebsd": true, "hurd": true,
	"illumos": true, "ios": true, "js": true, "linux": true, "nacl": true, "netbsd": true, "openbsd": true,
	"plan9": true, "solaris": true, "wasip1": true, "windows": true, "zos": true,
	// Architectures.
	"386": true, "amd64": true, "amd64p32": true, "arm": true, "armbe": true, "arm64": true, "arm64be": true,
	"loong64": true, "mips": true, "mipsle": true, "mips64": true, "mips64le": true, "mips64p32": true,
	"mips64p32le": true, "ppc": true, "ppc64": true, "ppc64le": true, "riscv": true, "riscv64": true,
	"s390": true, "s390x": true, "sparc": true, "sparc64": true, "wasm": true,
}

// hasBuildSuffix reports whether the file stem ends in a part the Go tool
// reads as a build constraint.
func hasBuildSuffix(stem string) bool {
	i := strings.LastIndexByte(stem, '_')
	return i >= 0 && buildSuffixes[stem[i+1:]]
}

// RenderMigration renders m as an editable Go source file of package pkgName
// that registers the migration from init. The output is formatted as gofmt
// formats it.
func RenderMigration(pkgName string, m Migration) (string, error) {
	w := &writer{}
	body, err := w.migration(m)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	buf.WriteString("// Generated by djangogo makemigrations.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	buf.WriteString("import (\n")
	if w.usesJSON {
		buf.WriteString("\t\"encoding/json\"\n")
	}
	if w.usesTime {
		buf.WriteString("\t\"time\"\n")
	}
	buf.WriteString("\t\"github.com/oliverhaas/djangogo/migrations\"\n")
	if w.usesORM {
		buf.WriteString("\t\"github.com/oliverhaas/djangogo/orm\"\n")
	}
	buf.WriteString(")\n\n")
	buf.WriteString("func init() {\n\tmigrations.Register(")
	buf.WriteString(body)
	buf.WriteString(")\n}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return "", fmt.Errorf("migrations: format %s: %w", m.Key(), err)
	}
	return string(src), nil
}

// WriteMigration renders m and writes it to the directory dir, which is
// created when missing. It returns the path of the file.
func WriteMigration(dir, pkgName string, m Migration) (string, error) {
	src, err := RenderMigration(pkgName, m)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("migrations: create %q: %w", dir, err)
	}
	path := filepath.Join(dir, FileName(m.Name))
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		return "", fmt.Errorf("migrations: write %q: %w", path, err)
	}
	return path, nil
}

// writer renders migration values as Go source. Indentation is left to
// go/format.
type writer struct {
	// usesORM is set once the output names the orm package.
	usesORM bool
	// usesTime is set when a default literal references time.Duration.
	usesTime bool
	// usesJSON is set when a default literal references json.RawMessage.
	usesJSON bool
}

// migration renders the Migration literal.
func (w *writer) migration(m Migration) (string, error) {
	var b strings.Builder
	b.WriteString("migrations.Migration{\n")
	fmt.Fprintf(&b, "App: %q,\n", m.App)
	fmt.Fprintf(&b, "Name: %q,\n", m.Name)
	if m.Initial {
		b.WriteString("Initial: true,\n")
	}
	writeKeys(&b, "Dependencies", m.Dependencies)
	writeKeys(&b, "RunBefore", m.RunBefore)
	ops, err := w.operations(m.Operations)
	if err != nil {
		return "", fmt.Errorf("%w (migration %s)", err, m.Key())
	}
	fmt.Fprintf(&b, "Operations: %s,\n", ops)
	b.WriteString("}")
	return b.String(), nil
}

// writeKeys renders a list of migration keys as the struct field name.
func writeKeys(b *strings.Builder, name string, keys []Key) {
	if len(keys) == 0 {
		return
	}
	fmt.Fprintf(b, "%s: []migrations.Key{\n", name)
	for _, k := range keys {
		fmt.Fprintf(b, "{App: %q, Name: %q},\n", k.App, k.Name)
	}
	b.WriteString("},\n")
}

// operations renders a list of operations.
func (w *writer) operations(ops []Operation) (string, error) {
	var b strings.Builder
	b.WriteString("[]migrations.Operation{\n")
	for _, op := range ops {
		src, err := w.operation(op)
		if err != nil {
			return "", err
		}
		b.WriteString(src)
		b.WriteString(",\n")
	}
	b.WriteString("}")
	return b.String(), nil
}

// operation renders one operation as a composite literal.
func (w *writer) operation(op Operation) (string, error) {
	var b strings.Builder
	switch o := op.(type) {
	case CreateModel:
		b.WriteString("migrations.CreateModel{\n")
		fmt.Fprintf(&b, "Name: %q,\n", o.Name)
		if o.Table != "" {
			fmt.Fprintf(&b, "Table: %q,\n", o.Table)
		}
		b.WriteString("Fields: []migrations.FieldState{\n")
		for _, f := range o.Fields {
			fmt.Fprintf(&b, "{%s},\n", w.fieldParts(f))
		}
		b.WriteString("},\n")
		if len(o.Indexes) > 0 {
			b.WriteString("Indexes: []migrations.Index{\n")
			for _, idx := range o.Indexes {
				fmt.Fprintf(&b, "{%s},\n", indexParts(idx))
			}
			b.WriteString("},\n")
		}
		if len(o.UniqueTogether) > 0 {
			fmt.Fprintf(&b, "UniqueTogether: %s,\n", fieldSets(o.UniqueTogether))
		}
		b.WriteString("}")
	case DeleteModel:
		fmt.Fprintf(&b, "migrations.DeleteModel{Name: %q}", o.Name)
	case RenameModel:
		fmt.Fprintf(&b, "migrations.RenameModel{OldName: %q, NewName: %q}", o.OldName, o.NewName)
	case AlterModelTable:
		fmt.Fprintf(&b, "migrations.AlterModelTable{Name: %q, Table: %q}", o.Name, o.Table)
	case AlterUniqueTogether:
		fmt.Fprintf(&b, "migrations.AlterUniqueTogether{\nName: %q,\n", o.Name)
		if len(o.UniqueTogether) > 0 {
			fmt.Fprintf(&b, "UniqueTogether: %s,\n", fieldSets(o.UniqueTogether))
		}
		b.WriteString("}")
	case AddIndex:
		fmt.Fprintf(&b, "migrations.AddIndex{\nModel: %q,\nIndex: migrations.Index{%s},\n}", o.Model, indexParts(o.Index))
	case RemoveIndex:
		fmt.Fprintf(&b, "migrations.RemoveIndex{Model: %q, Name: %q}", o.Model, o.Name)
	case AddField:
		oneOff, err := w.oneOffDefault(o.Default)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "migrations.AddField{\nModel: %q,\nField: migrations.FieldState{%s},\n%s}",
			o.Model, w.fieldParts(o.Field), oneOff)
	case RemoveField:
		fmt.Fprintf(&b, "migrations.RemoveField{Model: %q, Field: %q}", o.Model, o.Field)
	case AlterField:
		oneOff, err := w.oneOffDefault(o.Default)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "migrations.AlterField{\nModel: %q,\nField: migrations.FieldState{%s},\n%s}",
			o.Model, w.fieldParts(o.Field), oneOff)
	case RenameField:
		fmt.Fprintf(&b, "migrations.RenameField{Model: %q, OldName: %q, NewName: %q", o.Model, o.OldName, o.NewName)
		if o.Column != "" {
			fmt.Fprintf(&b, ", Column: %q", o.Column)
		}
		b.WriteString("}")
	case RunSQL:
		b.WriteString("migrations.RunSQL{\n")
		fmt.Fprintf(&b, "SQL: %s,\n", stringList(o.SQL))
		// An empty list means "nothing to undo", a missing one "irreversible".
		if o.ReverseSQL != nil {
			fmt.Fprintf(&b, "ReverseSQL: %s,\n", stringList(o.ReverseSQL))
		}
		if len(o.StateOperations) > 0 {
			ops, err := w.operations(o.StateOperations)
			if err != nil {
				return "", err
			}
			fmt.Fprintf(&b, "StateOperations: %s,\n", ops)
		}
		b.WriteString("}")
	default:
		return "", fmt.Errorf("%w: %T", ErrNotSerializable, op)
	}
	return b.String(), nil
}

// fieldParts renders the key-value pairs of a FieldState literal. Zero values
// are left out to keep the line short.
func (w *writer) fieldParts(f FieldState) string {
	w.usesORM = true
	parts := []string{
		fmt.Sprintf("Name: %q", f.Name),
		fmt.Sprintf("Column: %q", f.Column),
		"Kind: orm.Kind" + f.Kind.String(),
	}
	flag := func(set bool, name string) {
		if set {
			parts = append(parts, name+": true")
		}
	}
	flag(f.PrimaryKey, "PrimaryKey")
	flag(f.Null, "Null")
	flag(f.Unique, "Unique")
	if f.MaxLength != 0 {
		parts = append(parts, fmt.Sprintf("MaxLength: %d", f.MaxLength))
	}
	if f.MaxDigits != 0 {
		parts = append(parts, fmt.Sprintf("MaxDigits: %d", f.MaxDigits))
	}
	if f.DecimalPlaces != 0 {
		parts = append(parts, fmt.Sprintf("DecimalPlaces: %d", f.DecimalPlaces))
	}
	flag(f.DBIndex, "DBIndex")
	flag(f.Blank, "Blank")
	if f.Default != nil {
		parts = append(parts, "Default: "+w.defaultLiteral(f.Default))
	}
	flag(f.AutoNow, "AutoNow")
	flag(f.AutoNowAdd, "AutoNowAdd")
	if f.RelKind != orm.RelNone {
		parts = append(parts, "RelKind: "+relKindSource(f.RelKind))
	}
	if f.RelTo != "" {
		parts = append(parts, fmt.Sprintf("RelTo: %q", f.RelTo))
	}
	if f.RelOnDelete != orm.OnDeleteDoNothing {
		parts = append(parts, "RelOnDelete: "+onDeleteSource(f.RelOnDelete))
	}
	return strings.Join(parts, ", ")
}

// oneOffDefault renders the Default line of AddField and AlterField, or ""
// when there is none.
func (w *writer) oneOffDefault(v any) (string, error) {
	switch v.(type) {
	case nil:
		return "", nil
	case nowDefault:
		return "Default: migrations.Now,\n", nil
	case bool, int, int64, string:
		return "Default: " + literal(v) + ",\n", nil
	default:
		if line, ok := w.oneOffKindDefault(v); ok {
			return line, nil
		}
	}
	return "", fmt.Errorf("%w: one-off default of type %T", ErrNotSerializable, v)
}

// literal renders a default value. An integer is written with its type, so
// the value read back from the file equals the one the models produce.
func literal(v any) string {
	switch x := v.(type) {
	case bool:
		return strconv.FormatBool(x)
	case int:
		return fmt.Sprintf("int64(%d)", x)
	case int64:
		return fmt.Sprintf("int64(%d)", x)
	case string:
		return strconv.Quote(x)
	}
	return fmt.Sprintf("%#v", v)
}

// indexParts renders the key-value pairs of an Index literal.
func indexParts(idx Index) string {
	return fmt.Sprintf("Name: %q, Fields: %s", idx.Name, stringList(idx.Fields))
}

// stringList renders a []string literal on one line.
func stringList(items []string) string {
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = sourceString(s)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// sourceString renders a string literal. Text with line breaks, as SQL often
// has, is written as a raw string where it can be.
func sourceString(s string) string {
	if strings.Contains(s, "\n") && !strings.ContainsAny(s, "`\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// fieldSets renders a [][]string literal, one set per line.
func fieldSets(sets [][]string) string {
	var b strings.Builder
	b.WriteString("[][]string{\n")
	for _, set := range sets {
		quoted := make([]string, len(set))
		for i, s := range set {
			quoted[i] = strconv.Quote(s)
		}
		b.WriteString("{" + strings.Join(quoted, ", ") + "},\n")
	}
	b.WriteString("}")
	return b.String()
}

// onDeleteSource returns the name of the orm constant, so the file reads
// "orm.OnDeleteCascade" and not a number.
func onDeleteSource(od orm.OnDelete) string {
	switch od {
	case orm.OnDeleteCascade:
		return "orm.OnDeleteCascade"
	case orm.OnDeleteSetNull:
		return "orm.OnDeleteSetNull"
	case orm.OnDeleteRestrict:
		return "orm.OnDeleteRestrict"
	case orm.OnDeleteProtect:
		return "orm.OnDeleteProtect"
	default:
		return "orm.OnDeleteDoNothing"
	}
}

// relKindSource returns the name of the orm constant of a relation kind.
func relKindSource(k orm.RelKind) string {
	switch k {
	case orm.RelFK:
		return "orm.RelFK"
	case orm.RelO2O:
		return "orm.RelO2O"
	default:
		return "orm.RelNone"
	}
}
